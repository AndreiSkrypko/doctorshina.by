											<h2>Первые признаки износа шин автомабиля</h2>
<p>В этом разделе мы расскажем о то, на что необходимо обратить внимание в Ваших колесах, а именно на какие <b>визуальные дефекты шин</b>.</p>
<h3>Причины быстрого износа шин</h3>
<p><img style="max-width: 100%;width: 180px;border-radius: 6px; float:right;margin: 10px;" src="../images/iznos.jpg" alt="прокол колеса"></p>
<p>Не для кого не секрет, что правильный равномерный износ резины - это естественный износ. Но бываю случаи, когда шина изнашивается по центру колеса, а это значит, что эта часть больше всего имеет контакт с дорожным полотном.  Это говорит о том, что давление в шине не соответствует рекомендуемому производителем давлению в шинах. А также может быть следствием резких перепадов температуры, при которых давление в шинах может меняться.</p>
<h3>Признаки износа шин</h3>
<p><img style="max-width: 100%;width: 320px;border-radius: 6px; float:right;margin: 10px;" src="../images/valbuka.jpg" alt="прокол колеса"></p>
<p>Часто на шине можно увидеть <b>трещины</b> - это следствие управления транспортным средством – удар о бордюр, яму. Большие трещины по борту шины говорят о длительном эксплуатировании с недостаточным давлением. Также трещины на боковой поверхности могут быть следствием неправильного хранения резины либо возрасте (химический распад).</p>
<p><img style="max-width: 100%;width: 180px;border-radius: 6px; float:right;margin: 10px;" src="../images/valbuka1.jpg" alt="прокол колеса"></p>
<p>Не редкость визуально обнаружить <b>выпуклость на шине</b>, так называемую «грыжу шин». Это связано с внутренним повреждением слоя резины и происходит обычно от удара боковой части колеса о столб, бордюр. При ударе Вы можете не обнаружить ее сразу, поэтому не забудьте посмотреть позже, т.к. использовать такую резину крайне опасно. Такой резине необходим срочный ремонт либо замена!</p>
<p><img style="max-width: 100%;width: 180px;border-radius: 6px; float:right;margin: 10px;" src="../images/rovno.jpg" alt="прокол колеса"></p>
<p>Иногда на резине можно увидеть <b>вмятины</b>, при обнаружении которой Вам необходимо проверить подвеску вашего транспортного средства, возможно у вас плохие амортизаторы, хотя любая неисправная часть подвески автомобиля может стать причиной такой картины. Если Вы увидели диагональную вмятину, обратитесь к специалисту по сход-развалу, возможно он неправильно выставлен, что и ведет к деформации резины, кроме того, обратите внимание, возможно вы довольно часто перегружаете заднюю часть автомобиля, т.к. зачастую такие проблемы возникают на задних колесах автомобиля.</p>
<p>Самое опасное состояние покрышек - <b>недостаток давления  в шине</b>, вследствие чего износ вашей резины будет неравномерным, протектор внутренней и внешней будет подвержен повышенному износу. Также напоминаем Вам о необходимости проверки давления в шинах регулярно, особенно при резких перепадах температуры.</p>
<p>Существует и такой износ покрышки как <b>выпуклый износ</b> бокового протектора, при наличие которого следует проверить шаровые шарниры и подшипник колеса, а также втулку стабилизатора.
Зачастую можно встретить плоские пятна на поверхности шины, которые в основном образуются при резком торможении или заносе, также такие одинарные пятна могут появиться на покрышках автомобилей, которые долго были припаркованы.</p>
<p>Не всегда видимым является <b>износ передней кромки протектора</b>, для это необходимо провести рукой, если вы почувствуете,  что некоторые углы протектора более острые, а другие грани более гладкие - это признак реального износа, а не норма. На практике это самый распространенный износ резины, однако, из-за невозможности видимости данной проблемы, зачастую водители не обращают внимание.
Если Вы заметили, что на покрышке явный односторонний износ, так называемый «зализ», Вам необходимо срочно отрегулировать сход-развал, также данная ситуация имеет быть место при поврежденных пружинах, шаровых шарнирах и втулок подвески.</p>
<h3>Индикаторы износа шин</h3>
<p>Ну и конечно, следует понимать, что любая марка резины имеет свое свойство и свой износ в связи с чем, производители устанавливают <b>индикаторы износа покрышки</b>, если у вас на шине нет индикатора износа, то вы можете самостоятельно измерить глубину протектора. Глубина протектора для летней резины должна быть не меньше 1,6; 2 или 3 мм (в зависимости от производителя, в то время как для зимней резины минимально допустимая высота протектора должна быть 4-6 мм.</p>
<p>Изучив настоящую статью, Вы сможете избежать дополнительные затраты, связанные с заменой колес, т.к. в настоящее время это достаточно дорогостоящий атрибут, кроме того Вы можете самостоятельно определить причину и обратиться к специалисту для устранения дефектов и поломок.</p>
