											<h2>Ремонт прокола шин -  алгоритм действий</h2>

<p>Данная статья будет особо важна для начинающих водителей и автоледи.</p>
<p>Следует всегда помнить о безопасности, в связи  с чем, при наличии подозрения на неисправность колеса не стоит резко останавливаться, подыщите ровное место, лучше если это будет стоянка, остановка. Не забудьте включить «аварийку»  и поставить треугольный знак аварийной остановки, не лишним будет в темное время суток одеть жилет.</p>
<p>Ну вот, теперь можно спокойно осмотреть колесо и выявить проблему. Если колесо спустило и подкачать насосом не удается, значит помочь Вам сможет только запасное колесо, для этого необходимо достать имеющиеся в вашем транспортном средстве: домкрат и ключ для колесных гаек. Если у Вас таких инструментов нет-не отчаивайтесь, наверняка, на дороге найдется авто водитель со всем необходимым.</p>
<p><img style="max-width: 100%;width: 320px;border-radius: 6px; float:right;margin: 10px;" src="../images/prokol.jpg" alt="прокол колеса"></p>
<p>Итак, у Вас есть запасное колесо, домкрат и ключ для гаек. Не стоит забывать о двух важных правилах: автомобиль должен стоять на ровной, твердой местности с стояночным тормозом, в противном случае-быть беде! Запасное колесо положите под кузов автомобиля со стороны где поврежденное колесо, это предотвратит сильный удар, если соскочит домкрат и ослабьте колесные гайки ключом, но не до конца и не вынимайте. Теперь очень важно найти место «поддомкрачивания автомобиля» обозначено на усилителе порога, установите домкрат и приподнимите автомобиль до момента отсутствия соприкосновения колеса с поверхностью дорожного слоя. Колесо должно свободно вращаться. Теперь можете снять гайки с помощью ключа.</p>
<p>Первый процесс прошел для Вас удачно и Вы близки к завершению. Ответственный момент - снятие колеса, если не удается снять руками, попробуйте немного надавить ногой. Посадите запасное колесо на ступицу, установите колесные гайки и затяните без применения усилий. Процесс практически закончен, аккуратно опустите домкрат и снимите его, теперь следует затянуть гайки с усилием рук. Нот и готовы, вы освоили курс замены колеса! </p>
<p>Не забудьте проверить давление в Вашей новой шине, т.к. есть вероятность того, что давления там будет мало.</p>
